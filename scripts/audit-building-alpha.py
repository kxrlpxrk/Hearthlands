"""Audit installed PNG alpha bounds without modifying artwork. Optional authoring tool:
Python + Pillow. --write updates the small bounds manifest; --check detects stale data.
Not required by npm install/build/runtime. Alpha >= 1 includes antialiased edge pixels.
"""
from pathlib import Path
from PIL import Image
import argparse, hashlib, json
parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');parser.add_argument('--check',action='store_true');args=parser.parse_args()
root=Path(__file__).resolve().parents[1];rows={}
for path in sorted((root/'src/assets/buildings/png').glob('*.png')):
    image=Image.open(path)
    if image.mode!='RGBA': raise ValueError(f'{path.name}: expected RGBA')
    box=image.getchannel('A').getbbox()
    if box is None: raise ValueError(f'{path.name}: no visible pixels')
    x,y,right,bottom=box;rows[path.name]={'x':x,'y':y,'width':right-x,'height':bottom-y}
    print(json.dumps({'file':path.name,'pixels':image.size,'visibleBounds':rows[path.name],'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}))
content="// Generated by scripts/audit-building-alpha.py --write; alpha >= 1, pixel units.\nimport type {ImageBounds} from './types';\nexport const rasterBounds:Readonly<Record<string,ImageBounds>>="+json.dumps(rows,indent=2)+";\n"
output=root/'src/assets/buildings/rasterBounds.ts'
if args.write: output.write_text(content)
if args.check and (not output.exists() or output.read_text()!=content): raise SystemExit('Bounds manifest is stale: run audit-building-alpha.py --write and review.')
